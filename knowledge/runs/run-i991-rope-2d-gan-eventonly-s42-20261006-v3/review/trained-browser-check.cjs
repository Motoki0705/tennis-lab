const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('/tmp/coordinate-review-browser/node_modules/playwright');
const out='/home/kamimura/projects/tennis-lab/outputs/ball_refiner/review/rope-gan-20261006';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1600,height:1160}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ready=()=>page.waitForFunction(()=>!document.querySelector('#source').classList.contains('busy')&&!document.querySelector('#save-config').disabled);
 const saved=page.waitForResponse(r=>r.url().endsWith('/api/saved'));
 await page.goto('http://127.0.0.1:8786');
 const response=await saved;assert.equal(response.status(),200);const result=await response.json();await ready();
 for(const dim of [2,3]) assert.equal(await page.inputValue('#model-'+dim+'d'),`outputs:train/rope-${dim}d-gan-eventonly/20261006-v3-s42/logs/version_0/checkpoints/best.ckpt`);
 assert(result.scene.prediction_2d!==null&&result.scene.prediction_3d!==null);
 for(const key of ['noise_p95_px','jitter_sigma_px','outlier_probability','isolated_probability']) assert.equal(result.request.augmentation[key],0);
 assert.equal(result.source,'saved');
 await page.selectOption('#plot-mode','y');await page.click('#next-event');
 await page.screenshot({path:out+'/trained-2d-3d-coordinates.png',fullPage:true});
 await page.selectOption('#plot-mode','speed');await page.selectOption('#layout','separate');
 await page.screenshot({path:out+'/trained-2d-3d-speed.png',fullPage:true});
 const before=result.input_sha256;
 const infer=page.waitForResponse(r=>r.url().endsWith('/api/infer'),{timeout:60000});await page.click('#infer');
 const liveResponse=await infer;assert.equal(liveResponse.status(),200);const live=await liveResponse.json();await ready();
 assert.equal(live.input_sha256,before);
 assert.deepEqual(live.scene.prediction_2d,result.scene.prediction_2d);
 assert.deepEqual(live.scene.prediction_3d,result.scene.prediction_3d);
 assert.deepEqual(errors,[]);
 const summary={rally:result.request.rally,source:result.source,checkpoints:[result.request.checkpoint_2d,result.request.checkpoint_3d],augmentation:result.request.augmentation,input_sha256:before,metrics2d:result.scene.metrics_2d[0],metrics3d:result.scene.metrics_3d,savedMatchesLive:true,errors};
 fs.writeFileSync(out+'/trained-browser-summary.json',JSON.stringify(summary,null,2));
 console.log(JSON.stringify(summary));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
