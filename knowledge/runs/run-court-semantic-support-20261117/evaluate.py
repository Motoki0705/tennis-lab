"""CPU-only paired replay; the meiji4 phase requires an explicit source freeze."""
import argparse
from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import asdict
import hashlib
import importlib.util
import json
from pathlib import Path
import pickle
import sys
import time
from unittest.mock import patch
import cv2
import numpy as np
import torch

BASE=Path(__file__).resolve().parent
PREVIOUS=Path('outputs/tennis_scene/evaluate/court-fixed-support-rgb-20261117')
OUT=Path('outputs/tennis_scene/evaluate/court-semantic-support-20261117')
spec=importlib.util.spec_from_file_location('previous_evaluate',Path('knowledge/runs/run-court-fixed-support-rgb-20261117/evaluate.py'))
prior=importlib.util.module_from_spec(spec);spec.loader.exec_module(prior)
from src.tasks.court_detection.geometry.hybrid_homography import HybridHomographyConfig,estimate_hybrid_homography,project_candidate
from src.tasks.court_detection.geometry.homography import court_template_xy,COURT_HOMOGRAPHY_EDGES
from src.tasks.court_detection.geometry.line_evidence import LineEvidence
from src.tasks.court_detection.inference.regions import CourtRegionSearchConfig,assess_region_prediction


def source_digest():
    return {str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(Path('src/tasks/court_detection/geometry').glob('*.py'))}|{
      str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in [Path('src/tasks/court_detection/inference/regions.py'),Path('src/tennis_scene/configs/pipeline.yaml')]}


def process(record,tag,model_only):
    cv2.setNumThreads(1);torch.set_num_threads(1)
    dest=OUT/tag/record['key'];dest.mkdir(parents=True,exist_ok=True)
    if (dest/'evaluation.json').exists():return {'key':record['key'],'cached':True}
    started=time.monotonic();image=cv2.cvtColor(cv2.imread(str(PREVIOUS/'rgb'/record['key']/'frame.png')),cv2.COLOR_BGR2RGB)
    assert hashlib.sha256(image.tobytes()).hexdigest()==record['rgb_sha256']
    world=court_template_xy().astype(float);edges=np.array(COURT_HOMOGRAPHY_EDGES);candidates={'new_support':[],'new_rgb':[]};seconds={'new_support':0.,'new_rgb':0.}
    for index,region in enumerate(record['regions']):
        raw=dict(np.load(prior.OLD/record['old_raw_group']/record['key']/f'raw_{index:02d}.npz'))
        path=PREVIOUS/'line-evidence'/record['key']/f'evidence_{index:02d}.npz'
        # Every one of the 8,530 frozen regions has persisted evidence. Missing
        # files are an asset failure, never interpreted as a rejected court.
        assert path.is_file(), f'Missing frozen LINE evidence: {path}'
        evidence=prior.prepare(raw,path)
        def prepared(*args,**kwargs):
            if evidence is None:raise ValueError('insufficient_or_diffuse_line_evidence')
            return evidence
        observed=raw['raw_xy'].astype(float);observed[~raw['valid']]=np.nan
        with patch.object(LineEvidence,'from_probability',side_effect=prepared):
            tick=time.monotonic()
            geometry=estimate_hybrid_homography(world,observed,raw['scores'],raw['line_probability'],edges=edges,
                 image_size_hw=tuple(raw['image_size_hw']),config=HybridHomographyConfig())
            geometry_seconds=time.monotonic()-tick
            # Local data generated by this script; retained for diagnosis only.
            (dest/f'geometry_{index:02d}.pkl').write_bytes(pickle.dumps(geometry))
            prediction=prior.typed(raw,geometry)
            for mode,method in [('new_support','model')]+([] if model_only else [('new_rgb','rgb_paint')]):
                tick=time.monotonic();assessed=assess_region_prediction(prediction,image,tuple(region),CourtRegionSearchConfig(refinement_method=method))
                seconds[mode]+=geometry_seconds+time.monotonic()-tick
                matrix=geometry.matrix if method=='model' else assessed.paint.fitted_matrix
                points=None if matrix is None else project_candidate(matrix,world)+(np.array(region[:2]) if method=='model' else 0)
                quality=assessed.quality.diagnostics()
                candidates[mode].append({'region_index':index,'region':region,'points':points,
                   'accepted':bool(geometry.status=='ok' and quality['accepted'] and prior.area_ok(points,record)),
                   'geometry_valid':points is not None,'model_geometry_valid':geometry.matrix is not None,
                   'status':geometry.status if geometry.status!='ok' else ('ok' if quality['accepted'] else 'quality_rejected'),
                   'quality':quality,'model_score':None if geometry.best is None else geometry.best.score,
                   'selected':geometry.selected,'diagnostics':assessed.geometry_diagnostics()})
    # Labels are read after all fits and gates. No model function receives GT.
    refs=json.loads(prior.REF.read_text()) if record['dataset']=='meiji_4cam' else {}
    truth,mask,reference=prior.truth_for(record,refs)
    previous=json.loads((PREVIOUS/'evaluation'/record['key']/'evaluation.json').read_text())
    conditions=previous['conditions'];all_candidates=previous['candidates']
    for mode,values in candidates.items():
        if not values:continue
        values=[prior.label(c,truth,mask,record['source_size_hw']) for c in values]
        qualified=[c for c in values if c['accepted']]
        chosen=min(qualified or values,key=lambda c:(float('inf') if c['quality']['score'] is None else c['quality']['score'],c['region_index']))
        conditions[mode]={k:v for k,v in chosen.items() if k not in ('diagnostics','selected')}
        conditions[mode].update(any_correct_candidate=any(c['correct'] for c in values),any_correct_accepted_candidate=any(c['correct'] and c['accepted'] for c in values))
        all_candidates[mode]=values
    result={k:previous[k] for k in ('key','dataset','camera','clip_id','reference_source')}
    result.update(conditions=conditions,candidates=all_candidates,seconds=seconds,wall_seconds=time.monotonic()-started)
    tmp=dest/'evaluation.tmp';tmp.write_text(json.dumps(prior.clean(result),allow_nan=False));tmp.replace(dest/'evaluation.json')
    return {'key':record['key'],'seconds':result['wall_seconds']}


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--tag',required=True);parser.add_argument('--workers',type=int,default=10)
    parser.add_argument('--dataset');parser.add_argument('--keys',type=Path);parser.add_argument('--limit',type=int);parser.add_argument('--model-only',action='store_true')
    args=parser.parse_args();records=json.loads((PREVIOUS/'manifest.json').read_text())['records']
    records=[r for r in records if r['dataset']==args.dataset] if args.dataset else [r for r in records if r['dataset']!='meiji_4cam']
    if args.keys:
        keys=set(json.loads(args.keys.read_text()));records=[r for r in records if r['key'] in keys]
    if args.limit:records=records[:args.limit]
    if any(r['dataset']=='meiji_4cam' for r in records):
        frozen=json.loads((BASE/'freeze.json').read_text());assert frozen['files']==source_digest(),'source changed after freeze'
    manifest={'files':source_digest(),'hybrid':asdict(HybridHomographyConfig()),'region':asdict(CourtRegionSearchConfig()),'keys':[r['key'] for r in records],'model_only':args.model_only}
    dest=OUT/args.tag;dest.mkdir(parents=True,exist_ok=True);mp=dest/'protocol.json'
    if mp.exists():assert json.loads(mp.read_text())==manifest,'do not overwrite another experiment'
    else:mp.write_text(json.dumps(manifest,indent=2))
    start=time.monotonic()
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        futures=[pool.submit(process,r,args.tag,args.model_only) for r in records]
        for f in as_completed(futures):print(json.dumps(f.result()),flush=True)
    (dest/'complete.json').write_text(json.dumps({'count':len(records),'seconds':time.monotonic()-start}))
if __name__=='__main__':main()
