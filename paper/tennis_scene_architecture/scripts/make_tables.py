"""Generate the published LaTeX tables from SHA-256-pinned Git inputs."""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import subprocess
from functools import cache
from pathlib import Path
from typing import Any

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parents[1]


@cache
def sources() -> dict[str, dict[str, str]]:
    with (PAPER / "evidence" / "sources.tsv").open(
        encoding="utf-8", newline=""
    ) as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    index = {row["id"]: row for row in rows}
    if not index or len(index) != len(rows):
        raise ValueError("A source table with unique IDs is required")
    return index


@cache
def source_bytes(source_id: str) -> bytes:
    source = sources()[source_id]
    revision = f"{source['commit']}:{source['path']}"
    data = subprocess.check_output(["git", "show", revision], cwd=ROOT)
    if hashlib.sha256(data).hexdigest() != source["sha256"]:
        raise ValueError(f"SHA-256 mismatch for {source_id} ({revision})")
    return data


def read_csv(source_id: str) -> list[dict[str, str]]:
    return list(csv.DictReader(io.StringIO(source_bytes(source_id).decode("utf-8"))))


def read_json(source_id: str) -> Any:
    return json.loads(source_bytes(source_id))


def ev(claim: str, value: str | int) -> str:
    return rf"\ev{{{claim}}}{{{value}}}"


def fmt(value: str | float, decimals: int = 2) -> str:
    return f"{float(value):,.{decimals}f}"


def pct(value: str | float) -> str:
    return fmt(100 * float(value))


def count(value: str | int) -> str:
    return f"{int(value):,}"


def fraction(numerator: str | int, denominator: str | int) -> str:
    return f"{count(numerator)}/{count(denominator)}"


def table(columns: str, header: list[str], rows: list[list[str]]) -> str:
    if any(len(row) != len(header) for row in rows):
        raise ValueError("A table row has the wrong number of cells")

    def line(values: list[str]) -> str:
        return " & ".join(values) + r" \\"

    return "\n".join(
        [
            "% Generated by scripts/make_tables.py.",
            rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
            r"\toprule",
            line(header),
            r"\midrule",
            *(line(row) for row in rows),
            r"\bottomrule",
            r"\end{tabular}",
            "",
        ]
    )


def court_tables() -> dict[str, str]:
    scene_groups = ("B00", "B00・B01", "B00〜B02", "B00〜B03")
    scenes = [
        [
            ev("court-scenes", row["scenes"]),
            group,
            ev("court-scenes", fmt(row["real/kp_mean_distance_px"], 1)),
            ev("court-scenes", fmt(row["real/kp_median_distance_px"])),
        ]
        for group, row in zip(scene_groups, read_csv("scene-results"), strict=True)
    ]
    effects = {
        (row["split"], row["stratum"]): row
        for row in read_json("court-view-results")["effects"]
    }
    strata = [
        ("val", "all", "val 全体"),
        ("test", "all", "test 全体"),
        ("test", "challenging", "test 難視点の和集合"),
        ("test", "low_angle", "test 低角"),
        ("test", "oblique", "test 斜め向き"),
        ("test", "cropped", "test 見切れ"),
    ]
    viewpoints = []
    for split, stratum, label in strata:
        row = effects[split, stratum]
        means = row["seed_means"]
        values = [
            fraction(row["images"], row["videos"]),
            "/".join(fmt(means[c]["kp_mean_px512"]) for c in ("narrow", "broad")),
            "/".join(fmt(means[c]["h_formed_pct"]) for c in ("narrow", "broad")),
        ]
        viewpoints.append([label, *(ev("court-views", value) for value in values)])
    return {
        "court_scenes": table(
            "rlrr", ["シーン数", "組合せ", "KP平均 [px]", "KP中央値 [px]"], scenes
        ),
        "court_viewpoints": table(
            "lrrr",
            ["集合", "画像/動画", "KP平均 狭/広 [px]", r"H成立率 狭/広 [\%]"],
            viewpoints,
        ),
    }


SELECTION = [
    ("image_2d", "画像上の順位付け"),
    ("court_raw_dwell", "コート滞在（raw ID）"),
    ("court_standard", "コート滞在＋連結"),
]


def tracking_tables() -> dict[str, str]:
    history = {row["variant"]: row for row in read_csv("tracking-data")}
    variants = [
        ("strongsort_pp__clipreid_vitb16_market1501", "StrongSORT++"),
        ("strongsort_pp_pose__clipreid_vitb16_market1501", "StrongSORT++＋pose"),
        (
            "deep_ocsort_pose_aflink_gsi__clipreid_vitb16_market1501",
            r"\shortstack[l]{Deep OC-SORT＋pose／CLIP\\＋AFLink／GSI}",
        ),
    ]
    tracking = []
    for variant, label in variants:
        row = history[variant]
        values = [
            *(fmt(row[key], 3) for key in ("idf1", "group_idf1", "pair_f1")),
            fraction(row["matched_label_boxes"], row["label_boxes"]),
        ]
        tracking.append([label, *(ev("track-2d", value) for value in values)])

    selection3 = []
    summaries = read_json("selection3")["summary"]
    for key, cohort in (("dev", "開発"), ("reserved", "予約")):
        for variant, label in SELECTION:
            row = summaries[key][variant]
            values = [
                pct(row["boxes"]["player_precision"]),
                pct(row["boxes"]["player_recall"]),
                pct(row["group_id"]["idf1"]),
                pct(row["pair"]["f1"]),
                fraction(row["associated_clips"], row["clips"]),
            ]
            selection3.append(
                [cohort, label, *(ev("selection-3cam", value) for value in values)]
            )

    selection4 = []
    summary = read_json("selection4")["summary"]
    for variant, label in [("all_tracks", "選別なし"), *SELECTION]:
        row = summary[variant]
        values = [
            fraction(row["triangulated_clips"], row["clips"]),
            count(row["player_frames_3d"]),
            pct(row["player_frame_coverage"]),
        ]
        selection4.append([label, *(ev("selection-4cam", value) for value in values)])

    data3 = read_json("track3d3")["all_three"]
    data4 = read_json("track3d4")
    old, new = data4["legacy"], data4["multiview"]
    common = len(data4["common_unused_view_clips"])
    tracking3d = [
        [
            "4cam 完了クリップ",
            *(
                ev(
                    "track-3d-4cam",
                    fraction(
                        r["clip_complete"],
                        len(data4["legacy"]["noncomplete"]) + old["clip_complete"],
                    ),
                )
                for r in (old, new)
            ),
        ],
        [
            r"4cam 全員の有効配置 [\%]",
            *(ev("track-3d-4cam", pct(r["all_placed_ratio"])) for r in (old, new)),
        ],
        [
            f"4cam 共通{ev('track-3d-4cam', common)}本の再投影中央値 [px]",
            *(
                ev("track-3d-4cam", fmt(r["paired_clip_median_of_unused_medians_px"]))
                for r in (old, new)
            ),
        ],
        [
            r"3cam 予約未見のIDF1 [\%]",
            *(
                ev("track-3d-3cam", pct(data3[k]["idf1"]))
                for k in ("legacy", "multiview_projected")
            ),
        ],
        [
            r"3cam 予約未見の選別再現率 [\%]",
            *(
                ev("track-3d-3cam", pct(data3[k]["recall"]))
                for k in ("legacy", "multiview_projected")
            ),
        ],
    ]
    return {
        "tracking": table(
            "lrrrr",
            ["追跡方式", "raw IDF1", "group IDF1", "pair F1", "照合box"],
            tracking,
        ),
        "selection_3cam": table(
            "llrrrrr",
            [
                "集合",
                "選別",
                r"選手P [\%]",
                r"選手R [\%]",
                r"group IDF1 [\%]",
                r"pair F1 [\%]",
                "成立",
            ],
            selection3,
        ),
        "selection_4cam": table(
            "lrrr",
            ["選別", "三角測量完了", "有効選手フレーム", r"被覆率 [\%]"],
            selection4,
        ),
        "tracking_3d": table("lrr", ["測定項目", "旧経路", "3D時間追跡"], tracking3d),
    }


def ball_tables() -> dict[str, str]:
    footprint = {
        row["camera"]: row
        for row in read_csv("footprints-data")
        if row["width"] == "1920" and row["cohort"] == "all_sampled"
    }
    census = read_json("visibility-summary")["annotation_census"]
    audits = {
        row["camera"]: row
        for row in read_csv("visibility-totals")
        if row["stratum"] == "all"
    }
    cameras = [
        [
            camera,
            ev("ball-footprint", fraction(row["measured"], row["sampled"])),
            ev("ball-footprint", fmt(row["diameter_px_median"])),
            ev("ball-footprint", fmt(row["blur_proxy_px_median"])),
            ev("ball-visibility", count(census[camera]["outside_centres"])),
            ev(
                "ball-visibility",
                fraction(audits[camera]["visible"], audits[camera]["n"]),
            ),
        ]
        for camera, row in footprint.items()
        if camera != "all"
    ]

    history = []
    for row in read_csv("ball-history"):
        if row["series"] not in ("capacity", "long_sequence"):
            continue
        size = fmt(int(row["parameters"]) / 1_000_000, 1) if row["parameters"] else "—"
        rounds = (
            row["query_updates"]
            if row["series"] == "capacity"
            else row["cumulative_updates"]
        )
        claim = "ball-capacity" if row["series"] == "capacity" else "ball-length"
        values = [
            row["frames"],
            size,
            count(rounds),
            fmt(row["mean_error_px"]),
            fmt(row["p95_error_px"]),
        ]
        history.append([row["condition"], *(ev(claim, value) for value in values)])

    variants = {
        "x3d_t32": "X3D T32",
        "i935_t8": "i935 T8",
        "shape_baseline": "形状対照",
    }
    interventions = {
        "ordered": "通常",
        "repeat_anchor": "同一画像を反復",
        "shuffle_context": "周辺の順序入替え",
        "color_roundness_motion": "色・丸さ・背景差分",
    }
    context = []
    for row in read_csv("ball-intervention"):
        if row["source"] != "all":
            continue
        support = int(row["observed"])
        values = [
            fmt(row["mean_error_px"]),
            fmt(row["p95_error_px"]),
            fraction(round(support * float(row["within_distance_rate"])), support),
            pct(row["negative_fpr"]),
            pct(row["observed_fnr"]),
        ]
        context.append(
            [
                variants[row["model"]],
                interventions[row["condition"]],
                *(ev("ball-intervention", value) for value in values),
            ]
        )

    scores = {
        (row["dataset"], row["condition"], row["source"]): row
        for row in read_csv("ball-train-csv")
        if row["operating_point"] == "balanced"
    }
    validation = [
        scores["validation", condition, "all"]
        for condition in ("T1_rgb", "T8_rgb_mdd", "T32_rgb_mdd")
    ]
    columns = [
        "指標",
        f"{ev('ball-train-plan', 'T=1')} RGB",
        f"{ev('ball-train-plan', 'T=8')} RGB＋MDD",
        f"{ev('ball-train-plan', 'T=32')} RGB＋MDD",
    ]
    training = [
        [
            "平均位置誤差 [px]",
            *(ev("ball-train-val", fmt(r["mean_error_px"])) for r in validation),
        ],
        [
            "中央値位置誤差 [px]",
            *(ev("ball-train-val", fmt(r["median_error_px"])) for r in validation),
        ],
        [
            r"全validationの命中率 [\%]",
            *(ev("ball-train-val", pct(r["within_20px_rate"])) for r in validation),
        ],
        [r"存在F1 [\%]", *(ev("ball-train-val", pct(r["f1"])) for r in validation)],
    ]
    for source, name in (
        ("chat_annotation", "Chat"),
        ("meiji", "Meiji 3cam"),
        ("tracknet", "TrackNet game9"),
    ):
        training.append(
            [
                rf"{name}の命中率 [\%]",
                *(
                    ev(
                        "ball-train-sources",
                        pct(
                            scores["validation", r["condition"], source][
                                "within_20px_rate"
                            ]
                        ),
                    )
                    for r in validation
                ),
            ]
        )
    anchors = [scores["anchors", r["condition"], "all"] for r in validation]
    training.append(
        [
            r"固定アンカーの命中数（率 [\%]）",
            *(
                ev(
                    "ball-train-anchor",
                    f"{fraction(round(int(r['observed']) * float(r['within_20px_rate'])), r['observed'])}"
                    f"（{pct(r['within_20px_rate'])}）",
                )
                for r in anchors
            ),
        ]
    )
    return {
        "ball_cameras": table(
            "lrrrrr",
            ["視点", "計測成立", "径 [px]", "伸び [px]", "範囲外座標", "可視確認"],
            cameras,
        ),
        "ball_history": table(
            "lrrrrr",
            ["条件", "窓長", "百万parameter", "更新", "平均 [px]", "P95 [px]"],
            history,
        ),
        "ball_intervention": table(
            "llrrrrr",
            [
                "モデル",
                "入力",
                "平均 [px]",
                "P95 [px]",
                "命中",
                r"FPR [\%]",
                r"FNR [\%]",
            ],
            context,
        ),
        "ball_training": table("lrrr", columns, training),
    }


def experiment_tables() -> dict[str, str]:
    lovo = []
    methods = read_json("lovo-data")["methods"]
    for method, label in (
        ("pipeline_baseline", "基準"),
        ("without_loess", "LOESSなし"),
    ):
        for cohort, key in (("方式別", "lovo"), ("共通", "common_lovo")):
            row = methods[method][f"{key}_reprojection_by_reference_kind"][
                "evaluation"
            ]["all"]
            values = [
                fraction(row["count"], row["label_count"]),
                fmt(row["median"]),
                fmt(row["p90"]),
            ]
            lovo.append([label, cohort, *(ev("lovo", value) for value in values)])

    full = read_json("full-data")
    status = full["status_counts"]
    performance = read_json("full-performance")
    resources = performance["resources"]
    clips = [row for row in read_csv("full-clips") if row["status"] == "generated"]

    def coverage(prefix: str) -> str:
        valid = sum(int(row[f"{prefix}_count"]) for row in clips)
        eligible = sum(int(row[f"{prefix}_total"]) for row in clips)
        return f"{fraction(valid, eligible)}（{pct(valid / eligible)}" + r"\%）"

    full_video = [
        [
            "生成クリップ",
            ev(
                "full-timing",
                fraction(status["generated"], len(read_csv("full-clips"))),
            ),
        ],
        ["停止クリップ", ev("full-timing", status["failed"])],
        ["CLI wall [s]", ev("full-timing", fmt(performance["cli_wall_seconds"]))],
        [
            "Peak VRAM [GiB]",
            ev(
                "full-timing",
                fmt(resources["nvml"]["cuda:0"]["used_peak_bytes"] / (1 << 30)),
            ),
        ],
        [
            "Peak RSS [GiB]",
            ev("full-timing", fmt(resources["ram_rss_sampled_peak_bytes"] / (1 << 30))),
        ],
        ["有効3D関節点", ev("full-coverage", coverage("player_kp_3d_vis"))],
        ["有効SMPLフレーム", ev("full-coverage", coverage("player_smpl_valid"))],
    ]

    labels = ["C1 逐次PT", "C2 共有PT", "C3 横断バッチPT", "C4 横断バッチTRT"]
    runtime = []
    for label, row in zip(labels, read_csv("runtime-csv"), strict=True):
        values = [
            fmt(row["cli_wall_seconds"]),
            fmt(row["speedup_vs_c1"]),
            fmt(row["peak_vram_gib"]),
            fmt(row["peak_rss_gib"]),
            fraction(row["managed_model_loads"], row["managed_model_unloads"]),
        ]
        runtime.append([label, *(ev("runtime-metrics", value) for value in values)])
    parity = []
    totals = (row for row in read_csv("parity-csv") if row["clip_id"] == "total")
    for label, row in zip(labels, totals, strict=True):
        values = [
            count(row["common_valid_joint_points"]),
            fmt(1_000 * float(row["median_m"])),
            fmt(1_000 * float(row["p95_m"])),
            fmt(1_000 * float(row["max_m"]), 3),
            count(row["valid_smpl_frames"]),
        ]
        parity.append(
            [label.split()[0], *(ev("runtime-parity", value) for value in values)]
        )
    return {
        "lovo": table(
            "llrrr", ["方式", "集合", "採点点/対象点", "中央値 [px]", "P90 [px]"], lovo
        ),
        "full_video": table("lr", ["測定項目", "結果"], full_video),
        "runtime": table(
            "lrrrrr",
            ["条件（FP16）", "CLI [s]", "倍率", "VRAM [GiB]", "RSS [GiB]", "読込/解放"],
            runtime,
        ),
        "runtime_parity": table(
            "lrrrrr",
            ["条件", "共通関節点", "中央値 [mm]", "P95 [mm]", "最大 [mm]", "SMPL"],
            parity,
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="compare with the committed tables"
    )
    args = parser.parse_args()
    tables = court_tables() | tracking_tables() | ball_tables() | experiment_tables()
    for name, content in tables.items():
        path = PAPER / "tables" / f"{name}.tex"
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Table differs from pinned inputs: {path}")
        else:
            path.write_text(content, encoding="utf-8")
    print(
        f"{len(tables)} tables {'match' if args.check else 'generated from'} the pinned sources"
    )


if __name__ == "__main__":
    main()
