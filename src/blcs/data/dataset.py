"""Dataset classes for BLCS.

Provides a unified PyTorch Dataset implementation for ball trajectory data.
Supports loading from npz files generated by BLCSSceneGenerator for both
single-view and multiview modes.
"""

from __future__ import annotations

import json
import random as rng
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
import torch
from torch import Tensor
from torch.utils.data import Dataset

from src.blcs.data.types import BLCSBatch, BLCSMultiViewBatch, BLCSMultiViewSample, BLCSSample
from src.common.data.scene_cache import get_scene_cache, load_npz_scene
from src.common.dataset.augmentation import (
    add_gaussian_noise,
    random_visibility_dropout,
    scale_uv_with_visibility,
)
from src.common.dataset.collate import collate_padded_batch

if TYPE_CHECKING:
    from omegaconf import DictConfig


class BallTrajectoryDataset(Dataset):
    """Unified dataset for BLCS single-view and multiview training.

    Mode selection is controlled by `output_mode` (or `config.data.output_mode`):
    - `single`: returns `BLCSSample` (camera dimension squeezed)
    - `multiview`: returns `BLCSMultiViewSample` (camera dimension kept)
    """

    def __init__(
        self,
        scene_dir: str | Path | None = None,
        split_file: str | Path | None = None,
        config: DictConfig | None = None,
        augment: bool = True,
        output_mode: str | None = None,
        num_views: int | None = None,
        min_cameras: int | None = None,
    ) -> None:
        self.config = config or {}
        self.augment = augment

        data_cfg = self.config.get("data", {})
        self.output_mode = str(output_mode or data_cfg.get("output_mode", "single")).lower()
        if self.output_mode not in {"single", "multiview"}:
            raise ValueError(
                f"Invalid output_mode='{self.output_mode}'. Supported: ['single', 'multiview']"
            )

        self.min_seq_len = int(data_cfg.get("min_seq_len", 15))
        self.max_seq_len = int(data_cfg.get("max_seq_len", 120))
        self.camera_mode = str(data_cfg.get("camera_mode", "random")).lower()

        # Augmentation parameters
        aug_cfg = data_cfg.get("augmentation", {})
        self.uv_noise_std = float(aug_cfg.get("uv_noise_std", 0.005))
        self.vis_drop_prob = float(aug_cfg.get("visibility_drop_prob", 0.1))
        scale_range_cfg = aug_cfg.get("scale_range", [1.0, 1.0])
        if not isinstance(scale_range_cfg, (list, tuple)) or len(scale_range_cfg) != 2:
            raise ValueError(
                "augmentation.scale_range must be a list/tuple of two numbers: [min_scale, max_scale]."
            )
        self.scale_range = (float(scale_range_cfg[0]), float(scale_range_cfg[1]))
        if self.scale_range[0] <= 0 or self.scale_range[1] <= 0:
            raise ValueError(
                f"augmentation.scale_range must be positive, got {self.scale_range}."
            )
        if self.scale_range[0] > self.scale_range[1]:
            raise ValueError(
                f"augmentation.scale_range min must be <= max, got {self.scale_range}."
            )

        # Multiview parameters (also used as unified internal representation)
        default_num_views = 1 if self.output_mode == "single" else int(data_cfg.get("num_views", 2))
        default_min_cameras = 1 if self.output_mode == "single" else int(data_cfg.get("min_cameras", 2))
        self.num_views = int(num_views) if num_views is not None else default_num_views
        self.min_cameras = int(min_cameras) if min_cameras is not None else default_min_cameras

        # Range sampling (optional): [min, max] inclusive
        self.num_views_range: tuple[int, int] | None = None
        self.seq_len_range: tuple[int, int] | None = None
        if "num_views_range" in data_cfg:
            r = data_cfg["num_views_range"]
            self.num_views_range = (int(r[0]), int(r[1]))
        if "seq_len_range" in data_cfg:
            r = data_cfg["seq_len_range"]
            self.seq_len_range = (int(r[0]), int(r[1]))

        self.scene_dir = Path(scene_dir) if scene_dir else None
        if self.scene_dir is None:
            raise ValueError("scene_dir must be set for BallTrajectoryDataset.")

        self.cache_max_scenes = int(data_cfg.get("cache_max_scenes", 128))
        self._scene_cache = (
            get_scene_cache(load_fn=load_npz_scene, maxsize=self.cache_max_scenes)
            if self.cache_max_scenes > 0
            else None
        )

        scenes_subdir = self.scene_dir / "scenes"
        self.scenes_base = scenes_subdir if scenes_subdir.exists() else self.scene_dir

        if split_file:
            self.scenes = self._load_split_file(split_file)
        else:
            self.scenes = sorted(self.scenes_base.glob("*.npz"))

        self._filter_scenes_by_camera_count()

    def _load_split_file(self, split_file: str | Path) -> list[Path]:
        split_path = Path(split_file)
        if not split_path.exists() and not split_path.is_absolute():
            if split_path.parent == Path("."):
                split_path = self.scene_dir / split_file

        scenes: list[Path] = []
        with open(split_path) as f:
            for line in f:
                filename = line.strip()
                if filename:
                    scenes.append(self.scenes_base / filename)
        return scenes

    def _filter_scenes_by_camera_count(self) -> None:
        valid_scenes: list[Path] = []
        for scene_path in self.scenes:
            try:
                data = np.load(scene_path, allow_pickle=True)
                num_cameras = int(data["num_cameras"])
                if num_cameras >= self.min_cameras:
                    valid_scenes.append(scene_path)
            except Exception:
                continue

        print(
            f"BallTrajectoryDataset[{self.output_mode}]: {len(valid_scenes)}/{len(self.scenes)} "
            f"scenes have >= {self.min_cameras} cameras"
        )
        self.scenes = valid_scenes

    def _choose_seq_range(self, num_frames: int) -> tuple[int, int, int]:
        max_possible = min(self.max_seq_len, num_frames)
        if self.seq_len_range is not None:
            min_seq, max_seq = self.seq_len_range
            max_seq = min(max_seq, max_possible)
            min_seq = min(min_seq, max_seq)
            actual_seq_len = rng.randint(min_seq, max_seq)
        else:
            actual_seq_len = max_possible

        if actual_seq_len < self.min_seq_len:
            raise ValueError(
                f"Scene too short: seq_len {actual_seq_len} < min_seq_len {self.min_seq_len}."
            )

        if actual_seq_len < num_frames:
            if self.augment:
                start_frame = rng.randint(0, num_frames - actual_seq_len)
            else:
                start_frame = (num_frames - actual_seq_len) // 2
        else:
            start_frame = 0
        end_frame = start_frame + actual_seq_len
        return start_frame, end_frame, actual_seq_len

    def _choose_camera_indices(self, num_cameras: int) -> list[int]:
        if self.output_mode == "single":
            if self.camera_mode == "first":
                return [0]
            if self.camera_mode == "random":
                return [rng.randrange(num_cameras)]
            return [0]

        if self.num_views_range is not None:
            min_views, max_views = self.num_views_range
            max_possible_views = min(max_views, num_cameras)
            effective_min_views = min(min_views, max_possible_views)
            actual_num_views = rng.randint(effective_min_views, max_possible_views)
        else:
            actual_num_views = min(self.num_views, num_cameras)

        return rng.sample(range(num_cameras), actual_num_views)

    def _load_multiview_sample(self, path: Path) -> dict[str, Tensor]:
        data = self._scene_cache.get(path) if self._scene_cache is not None else load_npz_scene(path)

        meta_raw = data.get("meta", {})
        if isinstance(meta_raw, (bytes, bytearray)):
            meta_raw = meta_raw.decode("utf-8")
        if isinstance(meta_raw, str):
            meta = json.loads(meta_raw)
        else:
            meta = meta_raw if isinstance(meta_raw, dict) else {}

        num_cameras = int(data["num_cameras"])
        num_frames = int(meta["num_frames"])

        start_frame, end_frame, seq_len = self._choose_seq_range(num_frames)
        selected_cams = self._choose_camera_indices(num_cameras)

        ball_uv_list: list[Tensor] = []
        ball_vis_list: list[Tensor] = []
        court_kp_list: list[Tensor] = []
        court_vis_list: list[Tensor] = []

        for cam_idx in selected_cams:
            prefix = f"cam_{cam_idx}_"
            ball_uv = torch.from_numpy(data[f"{prefix}ball_uv"][start_frame:end_frame].copy()).float()
            ball_vis = torch.from_numpy(data[f"{prefix}ball_visible"][start_frame:end_frame].copy()).float()
            court_kp = torch.from_numpy(data[f"{prefix}court_kp_uv"]).float()
            court_vis = torch.from_numpy(data[f"{prefix}court_kp_visible"]).float()

            court_kp_expanded = court_kp.unsqueeze(0).expand(seq_len, -1, -1)
            court_vis_expanded = court_vis.unsqueeze(0).expand(seq_len, -1)

            ball_uv_list.append(ball_uv)
            ball_vis_list.append(ball_vis)
            court_kp_list.append(court_kp_expanded)
            court_vis_list.append(court_vis_expanded)

        sample: dict[str, Tensor] = {
            "ball_uv": torch.stack(ball_uv_list, dim=0),
            "ball_vis": torch.stack(ball_vis_list, dim=0),
            "ball_mask": torch.ones(len(selected_cams), seq_len, dtype=torch.float32),
            "court_kp": torch.stack(court_kp_list, dim=0),
            "court_vis": torch.stack(court_vis_list, dim=0),
            "position_3d": torch.from_numpy(data["ball_pos_norm"][start_frame:end_frame].copy()).float(),
            "velocity_3d": torch.from_numpy(data["ball_vel_world"][start_frame:end_frame].copy()).float(),
            "seq_len": torch.tensor(seq_len, dtype=torch.long),
        }
        return sample

    def _apply_augmentation_multiview(
        self, sample: dict[str, Tensor]
    ) -> dict[str, Tensor]:
        sample = {k: (v.clone() if isinstance(v, Tensor) else v) for k, v in sample.items()}
        scale_min, scale_max = self.scale_range
        if not (scale_min == 1.0 and scale_max == 1.0):
            scale = rng.uniform(scale_min, scale_max)
            if abs(scale - 1.0) >= 1e-8:
                ball_uv = sample["ball_uv"]
                court_kp = sample["court_kp"]
                ball_vis = sample["ball_vis"]
                court_vis = sample["court_vis"]
                if not isinstance(ball_uv, Tensor) or not isinstance(court_kp, Tensor):
                    raise ValueError("ball_uv/court_kp must be tensors")
                if not isinstance(ball_vis, Tensor) or not isinstance(court_vis, Tensor):
                    raise ValueError("ball_vis/court_vis must be tensors")

                sample["ball_uv"], sample["ball_vis"] = scale_uv_with_visibility(
                    uv=ball_uv,
                    visibility=ball_vis,
                    scale=scale,
                )
                sample["court_kp"], sample["court_vis"] = scale_uv_with_visibility(
                    uv=court_kp,
                    visibility=court_vis,
                    scale=scale,
                )

        ball_uv = sample["ball_uv"]
        if isinstance(ball_uv, Tensor):
            sample["ball_uv"] = add_gaussian_noise(ball_uv, self.uv_noise_std).clamp(0, 1)

        court_kp = sample["court_kp"]
        if isinstance(court_kp, Tensor):
            sample["court_kp"] = add_gaussian_noise(court_kp, self.uv_noise_std).clamp(0, 1)

        ball_vis = sample["ball_vis"]
        if isinstance(ball_vis, Tensor):
            sample["ball_vis"] = random_visibility_dropout(ball_vis, self.vis_drop_prob)

        return sample

    def _to_single_sample(self, sample: dict[str, Tensor]) -> BLCSSample:
        # N=1 expected for single mode.
        ball_uv = sample["ball_uv"]
        ball_vis = sample["ball_vis"]
        court_kp = sample["court_kp"]
        court_vis = sample["court_vis"]
        if not isinstance(ball_uv, Tensor) or not isinstance(ball_vis, Tensor):
            raise ValueError("ball_uv/ball_vis must be tensors")
        if not isinstance(court_kp, Tensor) or not isinstance(court_vis, Tensor):
            raise ValueError("court_kp/court_vis must be tensors")

        if ball_uv.shape[0] != 1:
            raise ValueError(f"single mode requires N=1, got N={ball_uv.shape[0]}")

        position_3d = sample["position_3d"]
        velocity_3d = sample["velocity_3d"]
        seq_len = sample["seq_len"]
        if not isinstance(position_3d, Tensor) or not isinstance(velocity_3d, Tensor):
            raise ValueError("position_3d/velocity_3d must be tensors")
        if not isinstance(seq_len, Tensor):
            raise ValueError("seq_len must be tensor")

        return {
            "ball_uv": ball_uv[0],
            "ball_vis": ball_vis[0],
            "court_kp": court_kp[0, 0],
            "court_vis": court_vis[0, 0],
            "position_3d": position_3d,
            "velocity_3d": velocity_3d,
            "seq_len": seq_len,
        }

    def __len__(self) -> int:
        return len(self.scenes)

    def __getitem__(self, idx: int) -> BLCSSample | BLCSMultiViewSample:
        sample = self._load_multiview_sample(self.scenes[idx])

        if self.augment:
            sample = self._apply_augmentation_multiview(sample)

        if self.output_mode == "single":
            return self._to_single_sample(sample)

        return {
            "ball_uv": sample["ball_uv"],
            "ball_vis": sample["ball_vis"],
            "ball_mask": sample["ball_mask"],
            "court_kp": sample["court_kp"],
            "court_vis": sample["court_vis"],
            "position_3d": sample["position_3d"],
            "velocity_3d": sample["velocity_3d"],
            "seq_len": sample["seq_len"],
        }


def collate_trajectories(batch: list[BLCSSample]) -> BLCSBatch:
    """Collate function for variable-length single-view trajectories."""
    return collate_padded_batch(
        batch,
        sequence_keys=["ball_uv", "ball_vis", "position_3d", "velocity_3d"],
        static_keys=["court_kp", "court_vis"],
        seq_len_key="seq_len",
        mask_key="ball_mask",
    )


def collate_multiview_trajectories(
    batch: list[BLCSMultiViewSample],
) -> BLCSMultiViewBatch:
    """Collate function for multiview trajectory batches."""
    max_views = max(int(sample["ball_uv"].shape[0]) for sample in batch)
    max_seq_len = max(sample["seq_len"].item() for sample in batch)

    ball_uv_batch = []
    ball_vis_batch = []
    ball_mask_batch = []
    court_kp_batch = []
    court_vis_batch = []
    position_3d_batch = []
    velocity_3d_batch = []
    seq_len_batch = []
    for sample in batch:
        n_views = int(sample["ball_uv"].shape[0])
        seq_len = sample["seq_len"].item()
        pad_views = max_views - n_views
        pad_seq = max_seq_len - seq_len

        ball_uv = sample["ball_uv"]
        ball_vis = sample["ball_vis"]
        ball_mask = sample["ball_mask"]
        court_kp = sample["court_kp"]
        court_vis = sample["court_vis"]
        position_3d = sample["position_3d"]
        velocity_3d = sample["velocity_3d"]

        if pad_seq > 0:
            ball_uv = torch.cat([ball_uv, torch.zeros(n_views, pad_seq, 2)], dim=1)
            ball_vis = torch.cat([ball_vis, torch.zeros(n_views, pad_seq)], dim=1)
            ball_mask = torch.cat([ball_mask, torch.zeros(n_views, pad_seq)], dim=1)
            court_kp = torch.cat([court_kp, torch.zeros(n_views, pad_seq, 20, 2)], dim=1)
            court_vis = torch.cat([court_vis, torch.zeros(n_views, pad_seq, 20)], dim=1)
            position_3d = torch.cat([position_3d, torch.zeros(pad_seq, 3)], dim=0)
            velocity_3d = torch.cat([velocity_3d, torch.zeros(pad_seq, 3)], dim=0)

        if pad_views > 0:
            ball_uv = torch.cat([ball_uv, torch.zeros(pad_views, max_seq_len, 2)], dim=0)
            ball_vis = torch.cat([ball_vis, torch.zeros(pad_views, max_seq_len)], dim=0)
            ball_mask = torch.cat([ball_mask, torch.zeros(pad_views, max_seq_len)], dim=0)
            court_kp = torch.cat([court_kp, torch.zeros(pad_views, max_seq_len, 20, 2)], dim=0)
            court_vis = torch.cat([court_vis, torch.zeros(pad_views, max_seq_len, 20)], dim=0)

        ball_uv_batch.append(ball_uv)
        ball_vis_batch.append(ball_vis)
        ball_mask_batch.append(ball_mask)
        court_kp_batch.append(court_kp)
        court_vis_batch.append(court_vis)
        position_3d_batch.append(position_3d)
        velocity_3d_batch.append(velocity_3d)
        seq_len_batch.append(sample["seq_len"])
    return {
        "ball_uv": torch.stack(ball_uv_batch, dim=0),
        "ball_vis": torch.stack(ball_vis_batch, dim=0),
        "ball_mask": torch.stack(ball_mask_batch, dim=0),
        "court_kp": torch.stack(court_kp_batch, dim=0),
        "court_vis": torch.stack(court_vis_batch, dim=0),
        "position_3d": torch.stack(position_3d_batch, dim=0),
        "velocity_3d": torch.stack(velocity_3d_batch, dim=0),
        "seq_len": torch.stack(seq_len_batch, dim=0),
    }
