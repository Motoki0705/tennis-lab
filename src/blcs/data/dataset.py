def collate_trajectories(batch: list[BLCSSample]) -> BLCSBatch:
    """Collate function for variable-length trajectories.

    Pads sequences to the maximum length in the batch.

    Args:
        batch: List of sample dictionaries.

    Returns:
        Batched and padded tensors.

    """
    batch_size = len(batch)
    max_len = max(
        s["seq_len"].item() if isinstance(s["seq_len"], Tensor) else s["seq_len"]
        for s in batch
    )

    # Initialize padded tensors
    ball_uv = torch.zeros(batch_size, max_len, 2)
    ball_vis = torch.zeros(batch_size, max_len)
    ball_mask = torch.zeros(batch_size, max_len)
    position_3d = torch.zeros(batch_size, max_len, 3)
    velocity_3d = torch.zeros(batch_size, max_len, 3)
    court_kp = torch.zeros(batch_size, 20, 2)
    court_vis = torch.zeros(batch_size, 20)
    seq_lens = torch.zeros(batch_size, dtype=torch.long)

    for i, sample in enumerate(batch):
        seq_len = (
            sample["seq_len"].item()
            if isinstance(sample["seq_len"], Tensor)
            else sample["seq_len"]
        )
        ball_uv[i, :seq_len] = sample["ball_uv"][:seq_len]
        ball_vis[i, :seq_len] = sample["ball_vis"][:seq_len]
        ball_mask[i, :seq_len] = 1.0
        position_3d[i, :seq_len] = sample["position_3d"][:seq_len]
        velocity_3d[i, :seq_len] = sample["velocity_3d"][:seq_len]
        court_kp[i] = sample["court_kp"]
        court_vis[i] = sample["court_vis"]
        seq_lens[i] = seq_len

    return {
        "ball_uv": ball_uv,
        "ball_vis": ball_vis,
        "ball_mask": ball_mask,
        "court_kp": court_kp,
        "court_vis": court_vis,
        "position_3d": position_3d,
        "velocity_3d": velocity_3d,
        "seq_len": seq_lens,
    }
