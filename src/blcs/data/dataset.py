"""Dataset classes for BLCS.

Provides PyTorch Dataset implementations for ball trajectory data.
Supports loading from npz files generated by BLCSSceneGenerator.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
import torch
from torch import Tensor
from torch.utils.data import Dataset

from src.base.data.augmentation import add_gaussian_noise, random_visibility_dropout
from src.blcs.data.types import BLCSBatch, BLCSSample
from src.common.data.scene_cache import get_scene_cache, load_npz_scene

if TYPE_CHECKING:
    from omegaconf import DictConfig


class BallTrajectoryDataset(Dataset):
    """Dataset for ball trajectory estimation.

    Loads pre-generated scenes from disk (npz format).
    Supports train/val/test splits via split files.
    Supports multi-camera format with camera selection.
    """

    def __init__(
        self,
        scene_dir: str | Path | None = None,
        split_file: str | Path | None = None,
        config: DictConfig | None = None,
        augment: bool = True,
    ) -> None:
        """Initialize the dataset.

        Args:
            scene_dir: Directory containing pre-generated scenes (scenes/ subdir).
            split_file: Path to split file (train.txt, val.txt, test.txt).
            config: Configuration dictionary.
            augment: Apply data augmentation.

        """
        super().__init__()

        self.config = config or {}
        self.augment = augment

        data_cfg = self.config.get("data", {})
        self.min_seq_len = int(data_cfg.get("min_seq_len", 15))
        self.max_seq_len = int(data_cfg.get("max_seq_len", 120))
        self.cache_max_scenes = int(data_cfg.get("cache_max_scenes", 128))
        self._scene_cache = (
            get_scene_cache(load_fn=load_npz_scene, maxsize=self.cache_max_scenes)
            if self.cache_max_scenes > 0
            else None
        )

        # Camera selection mode: "random", "all", or camera index (int)
        self.camera_mode = data_cfg.get("camera_mode", "random")

        # Augmentation parameters
        aug_cfg = data_cfg.get("augmentation", {})
        self.uv_noise_std = aug_cfg.get("uv_noise_std", 0.005)
        self.vis_drop_prob = aug_cfg.get("visibility_drop_prob", 0.1)
        self.temporal_dropout_prob = aug_cfg.get("temporal_dropout_prob", 0.05)
        self.flip_horizontal = aug_cfg.get("flip_horizontal", True)

        # Load scene list
        self.scene_dir = Path(scene_dir) if scene_dir else None
        self.scenes: list[Path] = []

        if self.scene_dir:
            scenes_subdir = self.scene_dir / "scenes"
            if scenes_subdir.exists():
                self.scenes_base = scenes_subdir
            else:
                self.scenes_base = self.scene_dir

            if split_file:
                # Load from split file
                self.scenes = self._load_split_file(split_file)
            else:
                # Load all npz files
                self.scenes = sorted(self.scenes_base.glob("*.npz"))

    def _load_split_file(self, split_file: str | Path) -> list[Path]:
        """Load scene list from split file."""
        split_path = Path(split_file)
        if not split_path.is_absolute():
            if self.scene_dir is None:
                raise ValueError("scene_dir must be set to use relative split_file")
            split_path = self.scene_dir / split_file

        scenes = []
        with open(split_path) as f:
            for line in f:
                filename = line.strip()
                if filename:
                    scenes.append(self.scenes_base / filename)
        return scenes

    def _select_camera(self, num_cameras: int) -> int:
        """Select camera index based on camera_mode.

        Args:
            num_cameras: Number of available cameras in the scene.

        Returns:
            Selected camera index.

        """
        if self.camera_mode == "random":
            return np.random.randint(0, num_cameras)
        elif isinstance(self.camera_mode, int):
            return min(self.camera_mode, num_cameras - 1)
        else:
            return 0  # fallback to first camera

    def _load_scene(self, path: Path) -> dict[str, Tensor]:
        """Load a single scene from npz file (multi-camera format)."""
        data = (
            self._scene_cache.get(path)
            if self._scene_cache is not None
            else load_npz_scene(path)
        )

        # Parse metadata
        meta_raw = data.get("meta", {})
        if isinstance(meta_raw, (bytes, bytearray)):
            meta_raw = meta_raw.decode("utf-8")
        if isinstance(meta_raw, str):
            meta = json.loads(meta_raw)
        else:
            meta = meta_raw if isinstance(meta_raw, dict) else {}

        # Get number of cameras and select one
        num_cameras = int(data["num_cameras"])
        cam_idx = self._select_camera(num_cameras)
        prefix = f"cam_{cam_idx}_"

        # Convert to tensors
        return {
            "ball_uv": torch.from_numpy(data[f"{prefix}ball_uv"]).float(),
            "ball_vis": torch.from_numpy(data[f"{prefix}ball_visible"]).float(),
            "court_kp": torch.from_numpy(data[f"{prefix}court_kp_uv"]).float(),
            "court_vis": torch.from_numpy(data[f"{prefix}court_kp_visible"]).float(),
            "position_3d": torch.from_numpy(data["ball_pos_norm"]).float(),
            "velocity_3d": torch.from_numpy(data["ball_vel_world"]).float(),
            "seq_len": torch.tensor(meta["num_frames"]),
            "meta": meta,
        }

    def __len__(self) -> int:
        """Return dataset length."""
        return len(self.scenes)

    def __getitem__(self, idx: int) -> BLCSSample:
        """Get a single sample.

        Returns:
            Sample dictionary containing:
                - ball_uv: (T, 2) Ball 2D trajectory
                - ball_vis: (T,) Ball visibility flags
                - court_kp: (20, 2) Court 2D keypoints
                - court_vis: (20,) Court keypoint visibility
                - position_3d: (T, 3) GT 3D trajectory (normalized)
                - velocity_3d: (T, 3) Velocities
                - seq_len: Sequence length

        """
        sample = self._load_scene(self.scenes[idx])

        # Apply augmentation
        if self.augment:
            sample = self._apply_augmentation(sample)

        # Return standardized format
        return {
            "ball_uv": sample["ball_uv"],
            "ball_vis": sample["ball_vis"],
            "court_kp": sample["court_kp"],
            "court_vis": sample["court_vis"],
            "position_3d": sample["position_3d"],
            "velocity_3d": sample["velocity_3d"],
            "seq_len": sample["seq_len"],
        }

    def _apply_augmentation(self, sample: dict[str, Tensor]) -> dict[str, Tensor]:
        """Apply data augmentation to a sample."""
        sample = {
            k: v.clone() if isinstance(v, Tensor) else v for k, v in sample.items()
        }

        seq_len = (
            sample["seq_len"].item()
            if isinstance(sample["seq_len"], Tensor)
            else sample["seq_len"]
        )

        # Add Gaussian noise to UV coordinates
        sample["ball_uv"] = add_gaussian_noise(sample["ball_uv"], self.uv_noise_std)
        sample["ball_uv"] = sample["ball_uv"].clamp(0, 1)

        sample["court_kp"] = add_gaussian_noise(sample["court_kp"], self.uv_noise_std)
        sample["court_kp"] = sample["court_kp"].clamp(0, 1)

        # Random visibility dropout for ball
        sample["ball_vis"][:seq_len] = random_visibility_dropout(
            sample["ball_vis"][:seq_len], self.vis_drop_prob
        )

        # Temporal dropout (create gaps)
        if self.temporal_dropout_prob > 0:
            for i in range(seq_len):
                if torch.rand(1).item() < self.temporal_dropout_prob:
                    # Drop a few consecutive frames
                    gap_len = min(3, seq_len - i)
                    sample["ball_vis"][i : i + gap_len] = 0.0

        # Horizontal flip
        if self.flip_horizontal and torch.rand(1).item() > 0.5:
            # Flip ball UV (x coordinate)
            sample["ball_uv"][:, 0] = 1.0 - sample["ball_uv"][:, 0]
            # Flip court keypoints
            sample["court_kp"][:, 0] = 1.0 - sample["court_kp"][:, 0]
            # Flip 3D x coordinate
            sample["position_3d"][:, 0] = -sample["position_3d"][:, 0]
            if "velocity_3d" in sample:
                sample["velocity_3d"][:, 0] = -sample["velocity_3d"][:, 0]

        return sample


