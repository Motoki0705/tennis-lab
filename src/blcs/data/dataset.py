"""Dataset classes for BLCS.

Provides PyTorch Dataset implementations for ball trajectory data.
Supports loading from npz files generated by BLCSSceneGenerator.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
import torch
from torch import Tensor

from src.common.dataset.augmentation import add_gaussian_noise, random_visibility_dropout
from src.blcs.data.types import BLCSBatch, BLCSSample
from src.common.data.blcs_npz_adapter import load_3d_arrays, load_camera_view
from src.common.dataset.collate import collate_padded_batch
from src.common.dataset.npz_scene_dataset import NPZScene, NPZSceneDatasetBase, SceneDatasetConfig
from src.common.dataset.sequence import crop_to_max_len

if TYPE_CHECKING:
    from omegaconf import DictConfig


class BallTrajectoryDataset(NPZSceneDatasetBase[BLCSSample]):
    """Dataset for ball trajectory estimation.

    Loads pre-generated scenes from disk (npz format).
    Supports train/val/test splits via split files.
    Supports multi-camera format with camera selection.
    """

    def __init__(
        self,
        scene_dir: str | Path | None = None,
        split_file: str | Path | None = None,
        config: DictConfig | None = None,
        augment: bool = True,
    ) -> None:
        """Initialize the dataset.

        Args:
            scene_dir: Directory containing pre-generated scenes (scenes/ subdir).
            split_file: Path to split file (train.txt, val.txt, test.txt).
            config: Configuration dictionary.
            augment: Apply data augmentation.

        """
        self.config = config or {}
        self.augment = augment

        data_cfg = self.config.get("data", {})
        self.min_seq_len = int(data_cfg.get("min_seq_len", 15))
        self.max_seq_len = int(data_cfg.get("max_seq_len", 120))
        camera_mode = data_cfg.get("camera_mode", "random")

        # Augmentation parameters
        aug_cfg = data_cfg.get("augmentation", {})
        self.uv_noise_std = aug_cfg.get("uv_noise_std", 0.005)
        self.vis_drop_prob = aug_cfg.get("visibility_drop_prob", 0.1)
        self.temporal_dropout_prob = aug_cfg.get("temporal_dropout_prob", 0.05)
        self.flip_horizontal = aug_cfg.get("flip_horizontal", True)

        self.scene_dir = Path(scene_dir) if scene_dir else None
        if self.scene_dir is None:
            raise ValueError("scene_dir must be set for BallTrajectoryDataset.")
        crop_mode = "random" if self.augment else "center"
        super().__init__(
            config=SceneDatasetConfig(
                scene_dir=self.scene_dir,
                split=None,
                split_file=Path(split_file) if split_file is not None else None,
                min_seq_len=self.min_seq_len,
                max_seq_len=self.max_seq_len,
                cache_max_scenes=int(data_cfg.get("cache_max_scenes", 128)),
                camera_mode=camera_mode,
                crop_mode=crop_mode,
            )
        )

    def build_sample(self, scene: NPZScene) -> BLCSSample:
        """Get a single sample.

        Returns:
            Sample dictionary containing:
                - ball_uv: (T, 2) Ball 2D trajectory
                - ball_vis: (T,) Ball visibility flags
                - court_kp: (20, 2) Court 2D keypoints
                - court_vis: (20,) Court keypoint visibility
                - position_3d: (T, 3) GT 3D trajectory (normalized)
                - velocity_3d: (T, 3) Velocities
                - seq_len: Sequence length

        """
        view = load_camera_view(scene.data, scene.camera_idx)
        arrays = load_3d_arrays(
            scene.data,
            position_norm_key="ball_pos_norm",
            velocity_world_key="ball_vel_world",
        )
        ball_uv = torch.from_numpy(view.ball_uv).float()
        ball_vis = torch.from_numpy(view.ball_vis).float()
        court_kp = torch.from_numpy(view.court_kp).float()
        court_vis = torch.from_numpy(view.court_vis).float()
        position_3d = torch.from_numpy(arrays["ball_pos_norm"]).float()
        velocity_3d = torch.from_numpy(arrays["ball_vel_world"]).float()
        seq_len = min(scene.num_frames, int(ball_uv.shape[0]))
        if seq_len < self.min_seq_len:
            raise ValueError(
                f"Scene {scene.path} too short: seq_len {seq_len} < min_seq_len {self.min_seq_len}."
            )
        if ball_uv.shape[0] > self.max_seq_len:
            cropped, seq_len = crop_to_max_len(
                {
                    "ball_uv": ball_uv,
                    "ball_vis": ball_vis,
                    "position_3d": position_3d,
                    "velocity_3d": velocity_3d,
                },
                seq_len=seq_len,
                max_seq_len=self.max_seq_len,
                mode=self.config.crop_mode,
            )
            ball_uv = cropped["ball_uv"]
            ball_vis = cropped["ball_vis"]
            position_3d = cropped["position_3d"]
            velocity_3d = cropped["velocity_3d"]

        sample = {
            "ball_uv": ball_uv,
            "ball_vis": ball_vis,
            "court_kp": court_kp,
            "court_vis": court_vis,
            "position_3d": position_3d,
            "velocity_3d": velocity_3d,
            "seq_len": torch.tensor(seq_len, dtype=torch.long),
        }

        # Apply augmentation
        if self.augment:
            sample = self._apply_augmentation(sample)

        # Return standardized format
        return {
            "ball_uv": sample["ball_uv"],
            "ball_vis": sample["ball_vis"],
            "court_kp": sample["court_kp"],
            "court_vis": sample["court_vis"],
            "position_3d": sample["position_3d"],
            "velocity_3d": sample["velocity_3d"],
            "seq_len": sample["seq_len"],
        }

    def _apply_augmentation(self, sample: dict[str, Tensor]) -> dict[str, Tensor]:
        """Apply data augmentation to a sample."""
        sample = {
            k: v.clone() if isinstance(v, Tensor) else v for k, v in sample.items()
        }

        seq_len = (
            sample["seq_len"].item()
            if isinstance(sample["seq_len"], Tensor)
            else sample["seq_len"]
        )

        # Add Gaussian noise to UV coordinates
        sample["ball_uv"] = add_gaussian_noise(sample["ball_uv"], self.uv_noise_std)
        sample["ball_uv"] = sample["ball_uv"].clamp(0, 1)

        sample["court_kp"] = add_gaussian_noise(sample["court_kp"], self.uv_noise_std)
        sample["court_kp"] = sample["court_kp"].clamp(0, 1)

        # Random visibility dropout for ball
        sample["ball_vis"][:seq_len] = random_visibility_dropout(
            sample["ball_vis"][:seq_len], self.vis_drop_prob
        )

        # Temporal dropout (create gaps)
        if self.temporal_dropout_prob > 0:
            for i in range(seq_len):
                if torch.rand(1).item() < self.temporal_dropout_prob:
                    # Drop a few consecutive frames
                    gap_len = min(3, seq_len - i)
                    sample["ball_vis"][i : i + gap_len] = 0.0

        # Horizontal flip
        if self.flip_horizontal and torch.rand(1).item() > 0.5:
            # Flip ball UV (x coordinate)
            sample["ball_uv"][:, 0] = 1.0 - sample["ball_uv"][:, 0]
            # Flip court keypoints
            sample["court_kp"][:, 0] = 1.0 - sample["court_kp"][:, 0]
            # Flip 3D x coordinate
            sample["position_3d"][:, 0] = -sample["position_3d"][:, 0]
            if "velocity_3d" in sample:
                sample["velocity_3d"][:, 0] = -sample["velocity_3d"][:, 0]

        return sample


